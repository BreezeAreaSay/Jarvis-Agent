def _keyboard() -> list[Builtin]:
    c = "keyboard"
    out = [
        cmd(f"keyboard.{id_}", name, v(*phrases), [key(combo)], category=c, icon="keyboard")
        for id_, name, phrases, combo in _SHORTCUTS
    ]
    out += [
        cmd(f"keyboard.key_{id_}", name, v(*phrases), [key(k)], category=c, icon="keyboard")
        for id_, name, phrases, k in _KEYS
    ]
    for n in range(1, 13):
        word = _F_WORDS[n - 1]
        out.append(
            cmd(
                f"keyboard.key_f{n}",
                f"F{n}",
                v(
                    f"(нажми |)(f{n}|ф{n}|эф {word}|f {word}|эф{n})",
                    f"(нажми |)клавишу (f{n}|эф {word})",
                ),
                [key(f"f{n}")],
                category=c,
                icon="keyboard",
            )
        )
    out += [
        cmd(
            "keyboard.press",
            "Нажать клавиши",
            v(
                "нажми {keys}",
                "нажми (клавишу|клавиши|сочетание|комбинацию|кнопку) {keys}",
                "клавиша {keys}",
            ),
            [("Keys.Press", "{keys}")],
            category=c,
            icon="keyboard",
        ),
        cmd(
            "keyboard.type",
            "Напечатать текст",
            v(
                "напечатай {text}",
                "(напечатай|введи|набери|впиши) текст {text}",
            ),
            [("Keys.Type", "{text}")],
            category=c,
            icon="keyboard",
            chain=False,
        ),
        cmd(
            "keyboard.clipboard",
            "Скопировать в буфер",
            v("(скопируй|положи|запиши) в буфер (обмена|) {text}"),
            [("Clipboard.Set", "{text}")],
            category=c,
            icon="keyboard",
            chain=False,
        ),
    ]
    return out



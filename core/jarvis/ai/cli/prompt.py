"""Промпты для программ-провайдеров: системный промпт (файлом) и текст хода.

Системный промпт программа записывает в сессию при первом запросе и при продолжении сессии берёт оттуда же
(Claude Code: «System prompt flags in resumed conversations»), поэтому в нём только неизменные правила, а то,
что меняется (время, режим, профиль, память, характер, пожелания), идёт блоком <jarvis>…</jarvis> в начале
сообщения человека — так же, как additionalContext у ChatGPT (jarvis.ai.chatgpt.prompt).
"""

from jarvis.ai.prompts import RULES

CLI_RULES = """Ты работаешь внутри Jarvis — голосового ассистента на компьютере пользователя \
с Windows, а не в среде программирования. Терминала, файлов, правки кода и под-агентов у тебя нет; всё, что \
нужно сделать на компьютере, в заметках, календаре и интернете, делай только инструментами Jarvis \
(сервер MCP «jarvis»).
- Перед вызовом инструмента не пиши вступлений вроде «сейчас проверю» — сразу вызывай инструмент, а отвечай \
пользователю, когда результат готов.
- Блок <jarvis>…</jarvis> в начале сообщения пользователя — служебный контекст от Jarvis (время, режим, \
профиль, память, характер). Это не слова пользователя; раздел, пришедший позже, заменяет прежний.
- Блок «Ранее в этом чате» — пересказ прошлой переписки, а не новые просьбы."""

CLI_AGENT_RULES = """Ты работаешь внутри Jarvis как агент: управляешь компьютером пользователя с Windows \
только инструментами Jarvis (сервер MCP «jarvis»: снимок и картинка окна, клик по элементу или точке, ввод \
текста, прокрутка, клавиши, запуск программ и адресов, команды Jarvis, инструменты сервисов MCP, ожидание, \
finish). Терминала, файлов, правки кода и под-агентов нет. Между действиями не пиши пользователю — работай \
инструментами и в конце вызови finish с итогом."""

COMPLETE_TAIL = "Отвечай сразу текстом: инструментов в этом запросе нет."
JSON_ONLY = "Ответь только одним JSON-объектом — без пояснений, без markdown и без ```. Схема: {schema}"
NO_IMAGES = "(К сообщению приложены изображения, но эта программа их не получает.)"


def chat_system() -> str:
    """Системный промпт ходов чата."""
    return f"{CLI_RULES}\n\n{RULES}"


def agent_system(system: str) -> str:
    return f"{CLI_AGENT_RULES}\n\n{system}"


def turn_text(context: str, history: str, text: str) -> str:
    """Сообщение хода: служебный контекст, пересказ переписки (только в новой сессии) и слова человека."""
    parts = [f"<jarvis>\n{context}\n</jarvis>"] if context.strip() else []
    if history.strip():
        parts.append(history.strip())
    parts.append(text)
    return "\n\n".join(parts)

def _browser() -> list[Builtin]:
    c = "browser"
    out = [
        cmd(f"browser.{id_}", name, v(*phrases), [key(combo)], category=c, icon="site")
        for id_, name, phrases, combo in _BROWSER
    ]
    for n, (acc, nom, num) in enumerate(_ORDINALS, start=1):
        out.append(
            cmd(
                f"browser.tab_{n}",
                f"Вкладка {n}",
                v(
                    f"(перейди на |открой |на |)({acc} вкладку|{nom} вкладка)",
                    f"вкладка (номер |){num}",
                ),
                [key(f"ctrl+{n}")],
                category=c,
                icon="site",
            )
        )
    out += [
        cmd(
            "browser.last_tab",
            "Последняя вкладка",
            v("(перейди на |на |)последн(юю|яя) вкладк(у|а)"),
            [key("ctrl+9")],
            category=c,
            icon="site",
        ),
        cmd(
            "browser.open",
            "Открыть браузер",
            v("(открой|запусти|включи) браузер", "браузер"),
            [("Launch.Url", "https://www.google.com")],
            category=c,
            icon="site",
        ),
    ]
    return out


def commands() -> list[Builtin]:
    return [*_keyboard(), *_mouse(), *_browser()]

def _split(phrases: str) -> list[str]:
    """Разбить «a (b|c)|d» по «|» верхнего уровня (вне скобок)."""
    parts, depth, buf = [], 0, []
    for ch in phrases:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "|" and depth == 0:
            parts.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    parts.append("".join(buf))
    return [p.strip() for p in parts if p.strip()]


